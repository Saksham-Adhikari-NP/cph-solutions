int modpow (int b, int e) {
    int r = 1; b %= MOD;
    while (e > 0) {
        if (e & 1) r = r * b % MOD;
        b = b * b % MOD;
        e >>= 1;
    }
    return r;
}


void solve () 
{
    // solve here
    int n ; cin >> n ; 
    vi a(n) ; cin >> a; 
    sort(all(a)) ; 

    if (n == 1) { cout << a[0] % MOD <<endl; return; }
    if( a[n-1] == a[n-2] ) { cout << 1 << endl ; return; }
    int ans = a[n-1] % MOD;
    bool chain = true;
    for (int k = 1; k <= n - 1; k++) {
        if (k <= n - 2 && a[n-k-2] >= a[n-k-1]) chain = false;
        if (chain) {
            int base = (a[n-k-1] - 1) % MOD;
            ans = (ans + modpow(base, k + 1)) % MOD;
        }
    }
    cout << ans % MOD << '\n';


}

